import { readFile, mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "../../..");
const commonPath = path.join(repoRoot, "docs/contracts/common.schema.json");
const workflowPath = path.join(repoRoot, "docs/contracts/events/workflow-request.schema.json");
const domainPath = path.join(repoRoot, "docs/contracts/events/domain-event.schema.json");
const aguiPath = path.join(repoRoot, "docs/contracts/agui/stream.json");
const analyticsPath = path.join(repoRoot, "docs/contracts/analytics/events.schema.json");
const outDir = path.join(repoRoot, "contracts/ts/src/generated");

const common = JSON.parse(await readFile(commonPath, "utf8"));
const workflow = JSON.parse(await readFile(workflowPath, "utf8"));
const domain = JSON.parse(await readFile(domainPath, "utf8"));
const agui = JSON.parse(await readFile(aguiPath, "utf8"));
const analytics = JSON.parse(await readFile(analyticsPath, "utf8"));

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

function schemaWithDefs(name, def, extraDefs = {}) {
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    title: name,
    $defs: { ...common.$defs, ...extraDefs },
    ...def,
  };
}

const exports = [];
for (const [name, def] of Object.entries(common.$defs).sort(([a], [b]) => a.localeCompare(b))) {
  const ts = await compile(schemaWithDefs(name, def), name, {
    cwd: path.dirname(commonPath),
    bannerComment: "/* eslint-disable */",
    additionalProperties: false,
  });
  const file = path.join(outDir, `${name}.ts`);
  await writeFile(file, ts, "utf8");
  exports.push(`export type { ${name} } from "./generated/${name}.ts";`);
}

async function compileRoot(schema, name, cwd) {
  const ts = await compile(
    {
      ...schema,
      title: name,
      $defs: { ...common.$defs, ...(schema.$defs ?? {}) },
    },
    name,
    {
      cwd,
      bannerComment: "/* eslint-disable */",
      additionalProperties: false,
    },
  );
  await writeFile(path.join(outDir, `${name}.ts`), ts, "utf8");
  exports.push(`export type { ${name} } from "./generated/${name}.ts";`);
}

await compileRoot(workflow, "WorkflowRequest", path.dirname(workflowPath));
await compileRoot(domain, "DomainEvent", path.dirname(domainPath));
await compileRoot(analytics, "AnalyticsEvent", path.dirname(analyticsPath));

for (const [name, def] of Object.entries(agui.$defs).sort(([a], [b]) => a.localeCompare(b))) {
  if (typeof def.$ref === "string") {
    continue;
  }
  const ts = await compile(schemaWithDefs(name, def, { ...domain.$defs, ...agui.$defs }), name, {
    cwd: path.dirname(aguiPath),
    bannerComment: "/* eslint-disable */",
    additionalProperties: false,
  });
  await writeFile(path.join(outDir, `${name}.ts`), ts, "utf8");
  exports.push(`export type { ${name} } from "./generated/${name}.ts";`);
}

const index = `// Generated by make contracts; do not edit (ADR-008).\n${[...exports].sort().join("\n")}\n`;
await writeFile(path.join(repoRoot, "contracts/ts/src/index.ts"), index, "utf8");

console.log("contracts: regenerated TypeScript types");
