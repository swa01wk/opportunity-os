import { readFile, mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "../../..");
const commonPath = path.join(repoRoot, "docs/contracts/common.schema.json");
const workflowPath = path.join(repoRoot, "docs/contracts/events/workflow-request.schema.json");
const outDir = path.join(repoRoot, "contracts/ts/src/generated");

const common = JSON.parse(await readFile(commonPath, "utf8"));
const workflow = JSON.parse(await readFile(workflowPath, "utf8"));

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

function schemaWithDefs(name, def) {
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    title: name,
    $defs: common.$defs,
    ...def,
  };
}

const exports = [];
for (const [name, def] of Object.entries(common.$defs).sort(([a], [b]) => a.localeCompare(b))) {
  const ts = await compile(schemaWithDefs(name, def), name, {
    cwd: path.dirname(commonPath),
    bannerComment: "/* eslint-disable */",
    additionalProperties: false,
  });
  const file = path.join(outDir, `${name}.ts`);
  await writeFile(file, ts, "utf8");
  exports.push(`export type { ${name} } from "./generated/${name}.ts";`);
}

const workflowTs = await compile(
  {
    ...workflow,
    title: "WorkflowRequest",
    $defs: common.$defs,
  },
  "WorkflowRequest",
  {
    cwd: path.dirname(workflowPath),
    bannerComment: "/* eslint-disable */",
    additionalProperties: false,
  },
);
await writeFile(path.join(outDir, "WorkflowRequest.ts"), workflowTs, "utf8");
exports.push(`export type { WorkflowRequest } from "./generated/WorkflowRequest.ts";`);

const index = `// Generated by make contracts; do not edit (ADR-008).\n${exports.join("\n")}\n`;
await writeFile(path.join(repoRoot, "contracts/ts/src/index.ts"), index, "utf8");

console.log("contracts: regenerated TypeScript types");
